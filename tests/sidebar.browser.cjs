      assert(timing.hidden && timing.state, `${method}: filter panel hides synchronously`);
      assert(timing.duration<50, `${method}: close stays responsive (${timing.duration.toFixed(1)} ms)`);
      await page.evaluate(()=>__roomLoadFixture.releaseHistory());
      await page.waitForFunction(count=>__roomLoadFixture.activeMessageListeners().length===count,baseline);
