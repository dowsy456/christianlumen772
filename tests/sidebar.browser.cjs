        const started = performance.now();
        if(method==='close button') document.querySelector('#room-search-close').click();
        else document.body.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));
        return {duration:performance.now()-started,hidden:document.querySelector('#room-search-panel').hidden,state:ChatApp.roomSearchState===null};
